// Fails when project-authored text files contain non-ASCII characters.
// Client source files, third-party licence texts and future regional-language
// content are excluded on purpose.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';

const root = process.cwd();

const scanRoots = ['src', 'scripts', 'tests', 'docs/handover', 'drizzle'];
const rootFiles = [
  'README.md',
  'package.json',
  'next.config.ts',
  'sanity.config.ts',
  'sanity.cli.ts',
  'drizzle.config.ts',
  'playwright.config.ts',
  'vitest.config.mts',
  'eslint.config.mjs',
  'postcss.config.mjs',
  'tsconfig.json',
  '.env.example',
  '.gitignore',
];

const textExtensions = new Set([
  '.ts', '.tsx', '.mts', '.js', '.mjs', '.cjs', '.json', '.css', '.md', '.mdx',
  '.yml', '.yaml', '.svg', '.html', '.txt', '.sql', '.example',
]);

// Paths (relative, forward slashes) that may legitimately contain non-ASCII text.
const allowList = [
  /^src\/fonts\/.*\.txt$/, // OFL licence texts must stay verbatim
  /^src\/content\/locales\/(?!en\/)/, // future regional-language content
  /^drizzle\/meta\//, // generated by drizzle-kit
];

function toPosix(path) {
  return path.split(sep).join('/');
}

function walk(dir, out) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.next')) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else out.push(full);
  }
}

const files = [];
for (const dir of scanRoots) walk(join(root, dir), files);
for (const file of rootFiles) {
  const full = join(root, file);
  try {
    if (statSync(full).isFile()) files.push(full);
  } catch {
    // optional file not present
  }
}

// ASCII source that still renders typographic characters on the page.
const RENDERED_NON_ASCII = /&(?:[lr][sd]quo|[mn]dash|hellip|bull|middot|rarr|larr|copy|reg|trade|nbsp);|\\u(?:20[0-9a-f]{2}|00a0|00a9|2192)/i;

const problems = [];
for (const file of files) {
  const rel = toPosix(relative(root, file));
  const ext = extname(file) || (rel.endsWith('.env.example') ? '.example' : '');
  if (!textExtensions.has(ext) && !rel.startsWith('.')) continue;
  if (allowList.some((pattern) => pattern.test(rel))) continue;

  const lines = readFileSync(file, 'utf8').split('\n');
  lines.forEach((line, index) => {
    const entity = RENDERED_NON_ASCII.exec(line);
    if (entity && !rel.startsWith('scripts/check-ascii')) {
      problems.push(`${rel}:${index + 1}:${entity.index + 1}  renders as non-ASCII: ${entity[0]}`);
      return;
    }
    for (let col = 0; col < line.length; col += 1) {
      const code = line.charCodeAt(col);
      const isAllowedControl = code === 9 || code === 13;
      if ((code < 32 && !isAllowedControl) || code > 126) {
        const char = String.fromCodePoint(line.codePointAt(col) ?? code);
        const hex = (line.codePointAt(col) ?? code).toString(16).toUpperCase().padStart(4, '0');
        problems.push(`${rel}:${index + 1}:${col + 1}  U+${hex} ${JSON.stringify(char)}`);
        break; // one report per line is enough
      }
    }
  });
}

if (problems.length > 0) {
  console.error(`Non-ASCII characters found in ${problems.length} line(s):`);
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

console.log(`ASCII check passed (${files.length} files scanned).`);
